// Self-host the fonts (PRD 6.4): downloads Latin WOFF2 for Newsreader + Inter Tight, and subsets Noto Sans SC / Noto Serif SC
// to exactly the fixed UI copy. Run once: node tools/fetch_fonts.mjs   (needs internet; output goes to web/assets/fonts)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'web/assets/fonts');
fs.mkdirSync(OUT, { recursive: true });
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const get = async (u, bin) => { const r = await fetch(u, { headers: { 'user-agent': UA } }); if (!r.ok) throw new Error(`${r.status} ${u}`); return bin ? Buffer.from(await r.arrayBuffer()) : r.text(); };

// every CJK character that appears in fixed copy (shelf chrome, chapter titles, nav, buttons)
function fixedChars() {
  const files = [path.join(ROOT, 'web/js/shelf.js'), path.join(ROOT, 'web/js/main.js'), path.join(ROOT, 'server/seed.js'), path.join(ROOT, 'web/index.html')];
  const set = new Set('0123456789·/ ');
  for (const f of files) for (const ch of fs.readFileSync(f, 'utf8')) if (/[　-〿㐀-鿿＀-￯]/.test(ch)) set.add(ch);
  return [...set].join('');
}

let css = '/* generated by tools/fetch_fonts.mjs */\n';
async function family(name, spec, file, extra) {
  const text = await get(`https://fonts.googleapis.com/css2?family=${spec}&display=swap`);
  const blocks = [...text.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)];
  const latin = blocks.find((b) => b[1] === 'latin');
  if (!latin) throw new Error('no latin block for ' + name);
  const url = /url\(([^)]+)\)/.exec(latin[2])[1];
  const fn = file + '.woff2';
  fs.writeFileSync(path.join(OUT, fn), await get(url, true));
  css += latin[2].replace(/url\([^)]+\)/, `url(/assets/fonts/${fn})`) + '\n';
  console.log('✓', name, fn);
}
async function subset(name, spec, file, text) {
  const css2 = await get(`https://fonts.googleapis.com/css2?family=${spec}&text=${encodeURIComponent(text)}&display=swap`);
  const m = /@font-face\s*\{[^}]+\}/.exec(css2);
  const url = /url\(([^)]+)\)/.exec(m[0])[1];
  const fn = file + '.woff2';
  const buf = await get(url, true);
  fs.writeFileSync(path.join(OUT, fn), buf);
  css += m[0].replace(/url\([^)]+\)/, `url(/assets/fonts/${fn})`) + '\n';
  console.log('✓', name, fn, Math.round(buf.length / 1024) + ' KB');
}

try {
  await family('Newsreader 400', 'Newsreader:opsz,wght@6..72,400', 'newsreader-400');
  await family('Newsreader 400 italic', 'Newsreader:ital,opsz,wght@1,6..72,400', 'newsreader-400i');
  await family('Inter Tight 500', 'Inter+Tight:wght@500', 'intertight-500');
  await family('Inter Tight 600', 'Inter+Tight:wght@600', 'intertight-600');
  await subset('Noto Sans SC 500', 'Noto+Sans+SC:wght@500', 'notosanssc-500', fixedChars());
  await subset('Noto Serif SC 700', 'Noto+Serif+SC:wght@700', 'notoserifsc-700', '人工智能概论');
  fs.writeFileSync(path.join(OUT, 'fonts.css'), css);
  console.log('fonts.css written');
} catch (e) { console.error('字体下载失败（页面会回退到系统字体）:', e.message); process.exit(1); }
